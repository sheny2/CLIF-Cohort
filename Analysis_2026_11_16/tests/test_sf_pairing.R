#!/usr/bin/env Rscript
suppressPackageStartupMessages(library(data.table))
f<-sub('^--file=','',grep('^--file=',commandArgs(FALSE),value=TRUE)[1]);root<-dirname(dirname(normalizePath(f)))
source(file.path(root,'variable_rules.R'));source(file.path(root,'sf_pairing_helpers.R'))
t0<-as.POSIXct('2024-01-01',tz='UTC')
r<-data.table(hospital_block_id='A',recorded_dttm=t0+c(0,1,2,3)*3600,
 device_category=c('imv','nippv','imv','imv'),fio2_set=c(.5,NA,NA,.4))
s<-data.table(hospital_block_id='A',recorded_dttm=t0+c(.5,1.5,2.5,3.5,4.5,7,7.1)*3600,vital_value=c(95,95,95,95,98,97,95))
p<-build_sf_pairs(s,r)
stopifnot(p$sf_ratio[1]==190,all(is.na(p$sf_ratio[c(2,3,5,7)])),p$sf_ratio[4]==237.5,p$sf_ratio[6]==242.5)
g<-data.table(hospital_block_id='A',m=1:3,decision_dttm=t0+c(1.1,4.6,12)*3600)
a<-sf_pairs_to_grid(p,g)
stopifnot(all(is.na(a$sf_ratio)),a$sf_reason[1]=='Device changed since SpO2',a$sf_reason[2]=='SpO2 >97%')
stopifnot(identical(sf_categories(c(NA,301,300,250,200,120)),SF_LEVELS))
r2<-data.table(hospital_block_id='B',recorded_dttm=t0+2*3600,device_category='imv',fio2_set=.5)
s2<-data.table(hospital_block_id='B',recorded_dttm=t0+3600,vital_value=95)
stopifnot(is.na(build_sf_pairs(s2,r2)$sf_ratio))
stopifnot(all(sf_pairs_to_grid(build_sf_pairs(s,r[0]),g)$sf_category=='Undefined'))
cat('PASS: prior-only pairing, device episode reset/return, 4h boundary, high saturation, stale SpO2, and categorical boundaries.\n')

suppressPackageStartupMessages({library(arrow);library(data.table);library(dplyr)})
self <- sub('^--file=','',grep('^--file=',commandArgs(),value=TRUE)[1])
folder <- dirname(dirname(normalizePath(self)))
p <- parse(file.path(folder,'07_prepare_and_run_five_methods.R'))
expr <- Filter(function(e) is.call(e)&&identical(e[[1]],as.name('<-'))&&identical(e[[2]],as.name('read_selected')),as.list(p))
tmp <- tempfile();dir.create(tmp)
x <- data.table(hospitalization_id=rep(c('h1','h2','other'),each=1000),vital_category=rep(c('temperature','weight','spo2'),1000),vital_value=seq_len(3000))
write_parquet(x,file.path(tmp,'clif_vitals.parquet'))
e <- new.env(parent=globalenv());e$required_file<-function(f)file.path(tmp,f)
e$crosswalk<-data.table(hospitalization_id=c('h1','h2'))
eval(expr[[1]],envir=e)
Sys.setenv(PROPOSAL_READ_BATCH_ROWS='200')
z <- e$read_selected('clif_vitals.parquet',names(x),'vital_category','temperature')
want <- x[hospitalization_id %in% c('h1','h2')&vital_category=='temperature']
setorder(z,vital_value);setorder(want,vital_value)
stopifnot(identical(z,want))
z <- e$read_selected('clif_vitals.parquet',names(x),'vital_category','absent')
stopifnot(nrow(z)==0,setequal(names(z),names(x)))
unlink(tmp,recursive=TRUE)
cat('PASS: streamed Parquet filtering, multi-batch assembly and empty matches.\n')
